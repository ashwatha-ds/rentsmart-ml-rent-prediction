# =========================
# HEADER
# =========================
st.markdown('<div class="header">🏠 RentSmart</div>', unsafe_allow_html=True)
st.markdown('<div class="subheader">Chennai Rental Intelligence System</div>', unsafe_allow_html=True)

# =========================
# LOAD FILES
# =========================
model = pickle.load(open("model_final.pkl","rb"))
encoders = pickle.load(open("encoders_final.pkl","rb"))
df = pd.read_excel("FINALISED DATASET FOR PROJECT.xlsx")

# =========================
# SESSION STATE
# =========================
if "page" not in st.session_state:
    st.session_state.page = "intro"

if "option" not in st.session_state:
    st.session_state.option = None

# =========================
# NAVIGATION FUNCTIONS
# =========================
def go_to_selection():
    st.session_state.page = "selection"

def select_rent():
    st.session_state.option = "rent"
    st.session_state.page = "final"

def select_location():
    st.session_state.option = "location"
    st.session_state.page = "final"

def reset_search():
    st.session_state.page = "selection"
    st.session_state.option = None

# =========================
# INTRO PAGE
# =========================
if st.session_state.page == "intro":

    st.markdown('<div class="center">', unsafe_allow_html=True)

    st.markdown("### Welcome to RentSmart")
    st.markdown("Smart renting starts with the right information.")

    if st.button("➡ Get Started"):
        go_to_selection()

    st.markdown('</div>', unsafe_allow_html=True)

# =========================
# SELECTION PAGE
# =========================
elif st.session_state.page == "selection":

    st.markdown('<div class="center">', unsafe_allow_html=True)

    st.markdown("## What are you looking for?")

    col1, col2 = st.columns(2)

    with col1:
        if st.button("💰 Estimate Rent"):
            select_rent()

    with col2:
        if st.button("📍 Know Locations"):
            select_location()

    st.markdown('</div>', unsafe_allow_html=True)

# =========================
# FINAL PAGE
# =========================
elif st.session_state.page == "final":

    left, center, right = st.columns([1,2,1])

# =========================
# RENT ESTIMATION
# =========================
    if st.session_state.option == "rent":

        with center:

            st.subheader("Rent Estimation")

            zone = st.selectbox("Select Zone", df["ZONE"].unique())

            filtered_locations = df[df["ZONE"] == zone]["LOCATION"].unique()

            location = st.selectbox("Select Location", filtered_locations)

            property_type = st.selectbox("Property Type", df["PROPERTY_TYPE"].unique())

            bedrooms = st.selectbox("BHK", sorted(df["NO_OF_BEDROOMS"].unique()))

            furnishing = st.selectbox("Furnishing Status", df["FURNISHING_STATUS"].unique())

            parking = st.radio("Need Parking?", df["PARKING"].unique())

            lift = st.radio("Need Lift?", df["LIFT "].unique()) if property_type.lower() == "apartment" else "No"

            if property_type.lower() == "apartment":
                floor = st.selectbox("Floor", sorted(df["FLOOR"].dropna().unique()))
            else:
                floor = 0

            pets = st.radio("Pet Friendly?", df["PETS_ALLOWED"].unique())

            area = st.number_input("Built Area (sqft)")

            if st.button("Estimate Rent"):

                input_df = pd.DataFrame([{
                    "ZONE": zone,
                    "LOCATION": location,
                    "PROPERTY_TYPE": property_type,
                    "FLOOR": floor,
                    "NO_OF_BEDROOMS": bedrooms,
                    "FURNISHING_STATUS": furnishing,
                    "PARKING": parking,
                    "LIFT ": lift,
                    "PETS_ALLOWED": pets,
                    "BUILT_AREA": area
                }])

                for col in encoders:
                    input_df[col] = encoders[col].transform(input_df[col])

                pred_log = model.predict(input_df)[0]

                pred = np.expm1(pred_log)

                min_rent = int(pred * 0.9)
                max_rent = int(pred * 1.1)

                st.markdown(f"""
                <div class="rent-card">
                Estimated Monthly Rent<br><br>
                ₹ {min_rent:,} – ₹ {max_rent:,}
                </div>
                """, unsafe_allow_html=True)

            if st.button("🔄 Start Again"):
                reset_search()

# =========================
# LOCATION RECOMMENDATION
# =========================
    elif st.session_state.option == "location":

        with center:

            st.subheader("Location Recommendation")

            zone_r = st.selectbox("Preferred Zone", df["ZONE"].unique())

            property_type_r = st.selectbox("Property Type", df["PROPERTY_TYPE"].unique())

            budget = st.number_input("Enter Budget")

            bedrooms_r = st.selectbox("BHK", sorted(df["NO_OF_BEDROOMS"].unique()))

            furnishing_r = st.selectbox("Furnishing", df["FURNISHING_STATUS"].unique())

            parking_r = st.radio("Need Parking?", df["PARKING"].unique())

            lift_r = st.radio("Need Lift?", df["LIFT "].unique()) if property_type_r.lower() == "apartment" else "No"

            if st.button("Recommend Locations"):

                filtered = df.copy()

                filtered = filtered[filtered["ZONE"] == zone_r]
                filtered = filtered[filtered["PROPERTY_TYPE"] == property_type_r]
                filtered = filtered[filtered["NO_OF_BEDROOMS"] == bedrooms_r]
                filtered = filtered[filtered["FURNISHING_STATUS"] == furnishing_r]
                filtered = filtered[filtered["PARKING"] == parking_r]
                filtered = filtered[filtered["LIFT "] == lift_r]
                filtered = filtered[filtered["MONTHLY_RENT "] <= budget * 1.1]

                grouped = filtered.groupby("LOCATION").agg(avg_rent=("MONTHLY_RENT ", "mean")).reset_index()

                grouped["score"] = abs(grouped["avg_rent"] - budget)

                top3 = grouped.sort_values(by="score").head(3)

                if top3.empty:
                    st.warning("No matching locations found")

                else:
                    for _, row in top3.iterrows():

                        st.markdown(f"""
                        <div class="card">
                        <b>📍 {row['LOCATION']}</b><br>
                        💰 Average Rent ≈ ₹ {int(row['avg_rent']):,}
                        </div>
                        """, unsafe_allow_html=True)

            if st.button("🔄 Start Again"):
                reset_search()
